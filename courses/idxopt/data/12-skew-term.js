/* ---- 式を文字列で組み立てる補助（第10章と同じ式。ncdf は基盤の標準正規分布の累積分布関数） ---- */
const D1 = (S, K, r, T, s) => `((ln(${S} / ${K}) + (${r} + ${s} * ${s} / 2) * ${T}) / (${s} * sqrt(${T})))`;
const CALL = (S, K, r, T, s) => `(${S} * ncdf(${D1(S, K, r, T, s)}) - ${K} * exp(-${r} * ${T}) * ncdf(${D1(S, K, r, T, s)} - ${s} * sqrt(${T})))`;
const PUT = (S, K, r, T, s) => `(${CALL(S, K, r, T, s)} - ${S} + ${K} * exp(-${r} * ${T}))`;
/* 架空の IV の形：IV(K) ＝ ATM の IV ＋ 傾き × (K − 1,000) ÷ 100 ＋ 曲がり × ((K − 1,000) ÷ 100)²（％。下限 2％） */

/* 第07章のデータ。事実確認表・演習の照合・検算：facts/07-intrinsic-time-value.md（担当 OC、確認 2026-11-18）
この章は本質価値と時間価値の式（式 5・式 6）の持ち主（spec §9.1）。
実験台・演習・図の指数・価格はすべて架空（架空の指数 X、乗数 1,000 円）。実在の指数・オプションの価格・ボラティリティの水準は書かない。
spec §3 の第07章の「価格が本質価値より小さい組合せは理論上ありえない」は、ヨーロピアンのプットでは正確でない（下限は K × e^(−rT) − S で、本質価値より小さい）ので、
実験台の reads は「価格の下限より小さい」と「下限以上だが本質価値より小さい（ヨーロピアンのプット）」を分けた。 */

/* ---- 式を文字列で組み立てる補助（第10章と同じ式。ncdf は基盤の標準正規分布の累積分布関数） ---- */
const D1 = (S, K, r, T, s) => `((ln(${S} / ${K}) + (${r} + ${s} * ${s} / 2) * ${T}) / (${s} * sqrt(${T})))`;
const CALL = (S, K, r, T, s) => `(${S} * ncdf(${D1(S, K, r, T, s)}) - ${K} * exp(-${r} * ${T}) * ncdf(${D1(S, K, r, T, s)} - ${s} * sqrt(${T})))`;
const PUT = (S, K, r, T, s) => `(${CALL(S, K, r, T, s)} - ${S} + ${K} * exp(-${r} * ${T}))`;


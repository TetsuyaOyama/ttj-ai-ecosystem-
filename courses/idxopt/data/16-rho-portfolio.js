const D1 = (S, K, r, T, s) => `((ln(${S} / ${K}) + (${r} + ${s} * ${s} / 2) * ${T}) / (${s} * sqrt(${T})))`;
const D2 = (S, K, r, T, s) => `(${D1(S, K, r, T, s)} - ${s} * sqrt(${T}))`;
const CALL = (S, K, r, T, s) => `(${S} * ncdf(${D1(S, K, r, T, s)}) - ${K} * exp(-${r} * ${T}) * ncdf(${D2(S, K, r, T, s)}))`;
const PUT = (S, K, r, T, s) => `(${K} * exp(-${r} * ${T}) * ncdf(-${D2(S, K, r, T, s)}) - ${S} * ncdf(-${D1(S, K, r, T, s)}))`;
const RHO_C = (S, K, r, T, s) => `(${K} * ${T} * exp(-${r} * ${T}) * ncdf(${D2(S, K, r, T, s)}) / 100)`;
const RHO_P = (S, K, r, T, s) => `(-${K} * ${T} * exp(-${r} * ${T}) * ncdf(-${D2(S, K, r, T, s)}) / 100)`;

